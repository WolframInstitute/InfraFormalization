"""Additivity of path lengths in the hypergraph multiway example of arXiv:2301.04690
(papers/tex_2301_04690/ComputationalIrreducibility.tex line 657, Figures 13-16).

Line 657 states that in the category freely generated by the multiway evolution graph of
{{x,y},{x,z}} -> {{x,z},{x,w},{y,w},{z,w}} from a double self-loop, 3 steps, "the composition
and tensor product operations are not purely additive". The time complexity of a morphism
X -> Y is the number of rewrites needed (lines 114, 471), i.e. the least path length from X to Y.
Composition is additive when the least path length from X to Z through Y equals the least path
length from X to Z. The script runs HGEvolve with isomorphic states identified, and checks
(i) that every event joins a state with e edges to a state with e + 2 edges, so that every path
from X to Y has length (|E(Y)| - |E(X)|) / 2, and (ii) additivity over all triples X -> Y -> Z
directly from breadth-first distances."""
import collections
import json

from hg_env import evolve

RULE = ([["x", "y"], ["x", "z"]], [["x", "z"], ["x", "w"], ["y", "w"], ["z", "w"]])


def main():
    out = {}
    for steps in (3, 4):
        r = evolve([RULE], [[0, 0], [0, 0]], steps, canonicalize_states="Full")
        nedges = {}
        for s in r.states.records():
            nedges[s["CanonicalId"]] = len(s["Edges"])
        succ = collections.defaultdict(set)
        deltas = collections.Counter()
        for e in r.events.records():
            a, b = e["CanonicalInputState"], e["CanonicalOutputState"]
            succ[a].add(b)
            deltas[nedges[b] - nedges[a]] += 1
        dist = {}
        for s in nedges:
            d = {s: 0}
            q = collections.deque([s])
            while q:
                u = q.popleft()
                for v in succ[u]:
                    if v not in d:
                        d[v] = d[u] + 1
                        q.append(v)
            dist[s] = d
        triples = nonadd = 0
        for x in nedges:
            for y, dxy in dist[x].items():
                for z, dyz in dist[y].items():
                    triples += 1
                    if dist[x][z] != dxy + dyz:
                        nonadd += 1
        out[f"steps_{steps}"] = {"states": len(nedges), "events": r.num_events,
                                 "edge_count_change_per_event": dict(deltas),
                                 "reachable_triples": triples, "non_additive_triples": nonadd}
    print(json.dumps(out, indent=1))
    with open("../../../results/publication_review/irreducibility_additivity.json", "w") as f:
        json.dump(out, f, indent=1)


if __name__ == "__main__":
    main()
