"""Merge the declaration list of scripts/inventory.lean with the output of
its `#print axioms` file, and print counts.

Usage: python3 merge_inventory.py <decls.tsv> <axioms-output.txt> <out.tsv>

Output columns: kind, name, module, axiom class, flags, library constants in
the type, library constants in the value. Axiom class (theorems only):
clean (at most propext, Classical.choice, Quot.sound), native (an axiom
generated by native_decide, Lean.ofReduceBool or Lean.trustCompiler), sorry
(sorryAx), other, missing (no output line).
"""
import collections
import re
import sys

decls, axfile, out = sys.argv[1:4]
text = open(axfile).read()
axioms = {}
for m in re.finditer(r"'(\S+?)' (depends on axioms: \[([^\]]*)\]|does not depend on any axioms)", text, re.S):
    axioms[m.group(1)] = {a.strip() for a in (m.group(3) or "").replace("\n", " ").split(",") if a.strip()}

clean = {"propext", "Classical.choice", "Quot.sound"}


def classify(name):
    if name not in axioms:
        return "missing"
    ax = axioms[name]
    if "sorryAx" in ax:
        return "sorry"
    if ax & {"Lean.ofReduceBool", "Lean.trustCompiler"} or any("native_decide" in a for a in ax):
        return "native"
    if ax <= clean:
        return "clean"
    return "other"


rows = []
for line in open(decls):
    f = line.rstrip("\n").split("\t")
    kind, name, mod, flags, tyc, valc = (f + [""] * 6)[:6]
    cls = classify(name) if kind == "theorem" else ""
    rows.append((kind, name, mod, cls, flags, tyc, valc))
rows.sort(key=lambda r: (r[2], r[1]))
with open(out, "w") as fh:
    for r in rows:
        fh.write("\t".join(r) + "\n")

kinds = collections.Counter(r[0] for r in rows)
classes = collections.Counter(r[3] for r in rows if r[0] == "theorem")
flags = collections.Counter(fl.split(":")[0] for r in rows for fl in r[4].split(",") if fl)
print("declarations:", len(rows))
for k, v in sorted(kinds.items()):
    print(f"  {k}: {v}")
print("theorem axiom classes:")
for k, v in sorted(classes.items()):
    print(f"  {k}: {v}")
print("flags:")
for k, v in sorted(flags.items()):
    print(f"  {k}: {v}")
other = [r[1] for r in rows if r[3] in ("sorry", "other")]
if other:
    print("sorry or other axioms:", " ".join(other))
