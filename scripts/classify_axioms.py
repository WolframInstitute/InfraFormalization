"""Classify the output of `#print axioms` for the theorems cited in the prose.

Usage: python3 classify_axioms.py <axioms-output.txt> <cited.tsv> <out.md>

cited.tsv columns: full name, file:line, citing documents.

Status:
  PROVED                     axioms within propext, Classical.choice, Quot.sound
  PROVED-WITH-NATIVE-DECIDE  depends on Lean.ofReduceBool or Lean.trustCompiler
  BROKEN                     depends on sorryAx
  MISSING                    no axiom line printed
"""
import collections
import re
import sys


text = open(sys.argv[1]).read()
entries = {}
for m in re.finditer(r"'(\S+?)' (depends on axioms: \[([^\]]*)\]|does not depend on any axioms)", text, re.S):
    entries[m.group(1)] = [a.strip() for a in (m.group(3) or "").replace("\n", " ").split(",") if a.strip()]

clean = {"propext", "Classical.choice", "Quot.sound"}
counts = collections.Counter()
rows = []
for line in open(sys.argv[2]):
    name, loc, docs = (line.rstrip("\n").split("\t") + [""])[:3]
    if name not in entries:
        cls, note = "MISSING", ""
    else:
        ax = set(entries[name])
        note = ""
        if "sorryAx" in ax:
            cls = "BROKEN"
        elif ax & {"Lean.ofReduceBool", "Lean.trustCompiler"} or any("native_decide" in a for a in ax):
            cls = "PROVED-WITH-NATIVE-DECIDE"
        elif ax <= clean:
            cls = "PROVED"
        else:
            cls = "OTHER-AXIOM"
            note = ", ".join(sorted(ax - clean))
    counts[cls] += 1
    short = name.replace("InfraFormalization.", "", 1)
    rows.append((short, loc.replace("lean/InfraFormalization/", ""), cls, note, docs.replace(",", ", ")))

with open(sys.argv[3], "w") as out:
    out.write("# Status of the theorems cited in the documentation\n\n")
    out.write("Generated by `scripts/theorem_status.sh`. Each theorem whose name appears in backticks in a `.md` file of the repository is listed with the status printed by `#print axioms` after `lake build`.\n\n")
    out.write("- PROVED: kernel-checked, sorry-free, axioms at most `propext`, `Classical.choice`, `Quot.sound`.\n")
    out.write("- PROVED-WITH-NATIVE-DECIDE: depends on an axiom generated by `native_decide` (`*._native.native_decide.ax_*`); not axiom-clean.\n")
    out.write("- BROKEN: depends on `sorryAx`.\n\n")
    out.write("| Status | Count |\n|---|---:|\n")
    for k in ("PROVED", "PROVED-WITH-NATIVE-DECIDE", "BROKEN", "OTHER-AXIOM", "MISSING"):
        out.write(f"| {k} | {counts.get(k, 0)} |\n")
    out.write("\n| Theorem | File:line | Status | Note | Cited in |\n|---|---|---|---|---|\n")
    for short, loc, cls, note, docs in sorted(rows):
        out.write(f"| `{short}` | `{loc}` | {cls} | {note} | {docs} |\n")
for k, v in sorted(counts.items()):
    print(k, v)
