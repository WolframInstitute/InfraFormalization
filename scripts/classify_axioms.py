"""Classify the output of `#print axioms` for the theorems cited in the prose.

Usage: python3 classify_axioms.py <axioms-output.txt> <cited.tsv> <out.md>

cited.tsv columns: full name, file:line, citing documents, names of
target-independent definitions occurring in the statement.

Status:
  PROVED                     axioms within propext, Classical.choice, Quot.sound
  PROVED-WITH-NATIVE-DECIDE  depends on Lean.ofReduceBool or Lean.trustCompiler
  BROKEN                     depends on sorryAx
  VACUOUS                    PROVED or PROVED-WITH-NATIVE-DECIDE, and the
                             statement uses a definition that does not depend
                             on its target argument, or is listed in MANUAL_VACUOUS
  MISSING                    no axiom line printed
"""
import collections
import re
import sys

MANUAL_VACUOUS = {
    "InfraFormalization.Refutations.orthonormality_depends_on_form":
        "statement about functions on Bool",
    "InfraFormalization.Refutations.orthonormalising_form_not_unique":
        "statement about functions on Bool",
    "InfraFormalization.Refutations.becomes_is_underdetermined":
        "statement about 1/(n+1)",
    "InfraFormalization.Refutations.claim_is_vacuous_without_convergence_notion":
        "statement about the constant-True predicate",
    "InfraFormalization.Refutations.different_notions_give_different_limits":
        "statement about the constant-True predicate",
}

text = open(sys.argv[1]).read()
entries = {}
for m in re.finditer(r"'([^']+)' (depends on axioms: \[([^\]]*)\]|does not depend on any axioms)", text, re.S):
    entries[m.group(1)] = [a.strip() for a in (m.group(3) or "").replace("\n", " ").split(",") if a.strip()]

clean = {"propext", "Classical.choice", "Quot.sound"}
counts = collections.Counter()
rows = []
for line in open(sys.argv[2]):
    name, loc, docs, hits = (line.rstrip("\n").split("\t") + [""])[:4]
    if name not in entries:
        cls, note = "MISSING", ""
    else:
        ax = set(entries[name])
        note = ""
        if "sorryAx" in ax:
            cls = "BROKEN"
        elif ax & {"Lean.ofReduceBool", "Lean.trustCompiler"} or any("native_decide" in a for a in ax):
            cls = "PROVED-WITH-NATIVE-DECIDE"
        elif ax <= clean:
            cls = "PROVED"
        else:
            cls = "OTHER-AXIOM"
            note = ", ".join(sorted(ax - clean))
        if cls.startswith("PROVED") and (hits or name in MANUAL_VACUOUS):
            note = ("uses " + hits.replace(",", ", ")) if hits else MANUAL_VACUOUS[name]
            cls = "VACUOUS"
    counts[cls] += 1
    short = name.replace("InfraFormalization.", "", 1)
    rows.append((short, loc.replace("lean/InfraFormalization/", ""), cls, note, docs.replace(",", ", ")))

with open(sys.argv[3], "w") as out:
    out.write("# Status of the theorems cited in the documentation\n\n")
    out.write("Generated by `scripts/theorem_status.sh`. Each theorem whose name appears in backticks in a `.md` file of the repository is listed with the status printed by `#print axioms` after `lake build`.\n\n")
    out.write("- PROVED: kernel-checked, sorry-free, axioms at most `propext`, `Classical.choice`, `Quot.sound`.\n")
    out.write("- PROVED-WITH-NATIVE-DECIDE: depends on an axiom generated by `native_decide` (`*._native.native_decide.ax_*`); not axiom-clean.\n")
    out.write("- VACUOUS: proved, and the statement uses a definition that does not depend on its target (for example `HypergraphMetricOriginObligationStrong`, which holds for every metric), or the statement concerns an object other than the one its name refers to.\n")
    out.write("- BROKEN: depends on `sorryAx`.\n\n")
    out.write("VACUOUS is assigned mechanically from the list `VACUOUS_DEFS` in `scripts/cited_theorems.py` and a short manual list in this script. The documents record further VACUOUS findings for individual theorems that this rule labels PROVED or PROVED-WITH-NATIVE-DECIDE.\n\n")
    out.write("| Status | Count |\n|---|---:|\n")
    for k in ("PROVED", "PROVED-WITH-NATIVE-DECIDE", "VACUOUS", "BROKEN", "OTHER-AXIOM", "MISSING"):
        out.write(f"| {k} | {counts.get(k, 0)} |\n")
    out.write("\n| Theorem | File:line | Status | Note | Cited in |\n|---|---|---|---|---|\n")
    for short, loc, cls, note, docs in sorted(rows):
        out.write(f"| `{short}` | `{loc}` | {cls} | {note} | {docs} |\n")
for k, v in sorted(counts.items()):
    print(k, v)
